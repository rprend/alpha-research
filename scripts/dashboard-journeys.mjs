export function getDashboardJourney(id) {
  return DASHBOARD_JOURNEYS.find((candidate) => candidate.id === id) ?? null
}

function listSection(title, values) {
  return [
    `## ${title}`,
    '',
    ...(values.length > 0 ? values.map((value) => `- ${value}`) : ['None.']),
    '',
  ]
}

export function markdownForDashboardJourney(journey) {
  return [
    `# ${journey.id}: ${journey.title}`,
    '',
    '## URL Path',
    '',
    `\`${journey.path}\``,
    '',
    '## Product Step',
    '',
    journey.productStep,
    '',
    '## User Mind',
    '',
    journey.userMind,
    '',
    ...listSection('What The User Knows', journey.userKnows),
    ...listSection('What The User Does Not Know', journey.userDoesNotKnow),
    '## Trigger',
    '',
    journey.trigger,
    '',
    '## Correct Product Steering',
    '',
    journey.correctProductSteering,
    '',
    ...listSection('Failure Modes To Catch', journey.failureModes),
    ...listSection('Evidence To Capture', journey.evidenceToCapture),
    '## Judge Question',
    '',
    journey.judgeQuestion,
    '',
    '## Capture Steps',
    '',
    '```json',
    JSON.stringify(journey.steps, null, 2),
    '```',
    '',
  ].join('\n')
}
