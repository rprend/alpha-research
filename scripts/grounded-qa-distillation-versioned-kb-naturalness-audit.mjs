function auditQuestion(example) {
  const question = String(example.input?.question ?? "");
  const citations = example.output?.citations ?? [];
  const hasLineCitation = example.output?.answer_type === "abstain"
    ? true
    : citations.some((id) => /@[\da-f]{12}:L\d+/.test(String(id)));
  const templateQuestion = /^(In both KB snapshots|According to the eval KB snapshot|According to the train KB snapshot),/.test(question);
  const prefixLeakage = /line beginning "/.test(question);
  const snapshotLabel = /\b(train|eval) KB snapshot\b/.test(question);
  const synthesis = /\b(compare|why|how|relationship|tradeoff|trend|summari[sz]e|across)\b/i.test(question);
  return {
    id: example.id,
    example_type: example.example_type,
    question,
    has_line_citation: hasLineCitation,
    template_question: templateQuestion,
    prefix_leakage: prefixLeakage,
    snapshot_label_in_question: snapshotLabel,
    synthesis_question: synthesis,
  };
}

function summarize(rows) {
  return {
    examples: rows.length,
    template_question_rate: ratio(rows.filter((row) => row.template_question).length, rows.length),
    prefix_leakage_rate: ratio(rows.filter((row) => row.prefix_leakage).length, rows.length),
    snapshot_label_rate: ratio(rows.filter((row) => row.snapshot_label_in_question).length, rows.length),
    synthesis_question_rate: ratio(rows.filter((row) => row.synthesis_question).length, rows.length),
    line_citation_rate: ratio(rows.filter((row) => row.has_line_citation).length, rows.length),
    by_type: Object.fromEntries([...new Set(rows.map((row) => row.example_type))].sort().map((type) => {
      const subset = rows.filter((row) => row.example_type === type);
      return [type, {
        examples: subset.length,
        template_question_rate: ratio(subset.filter((row) => row.template_question).length, subset.length),
        prefix_leakage_rate: ratio(subset.filter((row) => row.prefix_leakage).length, subset.length),
        snapshot_label_rate: ratio(subset.filter((row) => row.snapshot_label_in_question).length, subset.length),
        synthesis_question_rate: ratio(subset.filter((row) => row.synthesis_question).length, subset.length),
      }];
    })),
  };
}

function check(id, passed, evidence) {
  return { id, status: passed ? "pass" : "fail", evidence };
}

function renderReport(result) {
  return `# Versioned KB Naturalness Audit

Generated: ${result.generated_at}

Status: \`${result.status}\`

## Scorecard

| Check | Status | Evidence |
| --- | --- | --- |
${result.checks.map((row) => `| ${row.id} | ${row.status} | ${row.evidence} |`).join("\n")}

## Question Naturalness

- Template question rate: ${pct(result.aggregate.template_question_rate)}
- Prefix leakage rate: ${pct(result.aggregate.prefix_leakage_rate)}
- Snapshot-label rate: ${pct(result.aggregate.snapshot_label_rate)}
- Synthesis-question rate: ${pct(result.aggregate.synthesis_question_rate)}
- Line-citation rate: ${pct(result.aggregate.line_citation_rate)}

## Required Upgrade Artifacts

${result.required_upgrade_artifacts.map((item) => `- ${item}`).join("\n")}

## Paper Implication

${result.paper_implication}

This audit makes no OpenAI calls, launches no GPU jobs, and records no spend.
`;
}

async function readResult(id) {
  return readJson(path.join(runDir, id, "result.json"));
}

async function readJson(file) {
  return JSON.parse(await fs.readFile(file, "utf8"));
}

async function readJsonl(file) {
  const text = await fs.readFile(file, "utf8");
  return text.split("\n").filter((line) => line.trim()).map((line) => JSON.parse(line));
}

function parseArgs(values) {
  const parsed = {};
  for (const value of values) {
    const match = value.match(/^--([^=]+)=(.*)$/);
    if (match) parsed[match[1]] = match[2];
  }
  return parsed;
}

function ratio(numerator, denominator) {
  return denominator ? numerator / denominator : null;
}

function pct(value) {
  return value == null ? "n/a" : `${(100 * Number(value)).toFixed(1)}%`;
}
